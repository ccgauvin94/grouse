#!/usr/bin/env bash
#
# Build the macOS spike: the core as a universal static library + the Swift bindings,
# laid out as a SwiftPM package, then the `grouse-spike` CLI.
#
# RUN THIS ON macOS. It cannot work on the Linux build host: there is no Apple SDK, and
# `lipo`/`swift build` are Darwin tools. See README.md.
#
# What it does, in order:
#   1. builds `grouse-core` for BOTH Apple targets (arm64 + x86_64), release
#   2. builds it again in DEBUG for the host target only — and this is not a mistake:
#      the workspace's release profile sets `strip = true`, which removes the uniffi
#      metadata sections that bindgen reads. Same reason the Android script does it
#      (scripts/build-android-libs.sh: "the release profile strips the uniffi metadata").
#      The metadata is identical across profiles; only the ABI contract matters.
#   3. lipo → one universal libgrouse_core.a
#   4. uniffi-bindgen-swift → Swift sources + C headers
#   5. writes a plain (non-framework) module.modulemap, because SwiftPM's C targets want
#      one module per header rather than the framework map bindgen emits for Xcode
#   6. templates Package.swift with this checkout's absolute lib path, then builds
#
# Usage: ./build.sh [--no-build] [--host-only]
#   --no-build   regenerate + package + swift build, without rebuilding Rust
#   --host-only  build ONLY this machine's arch (no lipo, no second target). CI uses it:
#                a macOS runner is arm64, and cross-building x86_64 doubles a long Rust
#                build for a binary nobody runs there.

set -euo pipefail
cd "$(dirname "$0")"

SPIKE_DIR="$PWD"
REPO_ROOT="$(cd ../.. && pwd)"
CORE_DIR="$REPO_ROOT/core"
LIB_DIR="$SPIKE_DIR/build/lib"
GEN_SWIFT="$SPIKE_DIR/Sources/GrouseCore/Generated"
GEN_INCLUDE="$SPIKE_DIR/Sources/GrouseCoreFFI/include"
CMD=(run)
HOST_ONLY=0

for arg in "$@"; do
    case "$arg" in
        --no-build) CMD=(package) ;;
        --host-only) HOST_ONLY=1 ;;
        *) echo "usage: $0 [--no-build] [--host-only]" >&2; exit 2 ;;
    esac
done

HOST_TARGET="$([[ "$(uname -m)" == "arm64" ]] && echo aarch64-apple-darwin || echo x86_64-apple-darwin)"

# swift/uniffi are prerequisites, checked before any long Rust build.
for tool in cargo swift; do
    command -v "$tool" >/dev/null 2>&1 || {
        echo "error: $tool is required (run this on macOS)" >&2
        exit 1
    }
done
UNIFFI_BINDGEN="${UNIFFI_BINDGEN:-uniffi-bindgen-swift}"
command -v "$UNIFFI_BINDGEN" >/dev/null 2>&1 || {
    echo "error: $UNIFFI_BINDGEN not found. Install the CLI that matches the uniffi crate:"
    echo "  cargo install uniffi --features cli      # provides uniffi-bindgen-swift"
    echo "The committed Kotlin bindings were generated by uniffi 0.32.1; keep the CLI in step."
    exit 1
}

if [[ "${CMD[0]}" == "run" ]]; then
    mkdir -p "$LIB_DIR"
    if [[ "$HOST_ONLY" -eq 1 ]]; then
        echo "== Rust: release build for $HOST_TARGET only =="
        rustup target list --installed | grep -q "$HOST_TARGET" || rustup target add "$HOST_TARGET"
        cargo build --manifest-path "$CORE_DIR/Cargo.toml" --release -p grouse-core \
            --target "$HOST_TARGET"
        cp "$CORE_DIR/target/$HOST_TARGET/release/libgrouse_core.a" "$LIB_DIR/libgrouse_core.a"
    else
        echo "== Rust: release builds for both Apple targets =="
        rustup target list --installed | grep -q aarch64-apple-darwin || rustup target add aarch64-apple-darwin
        rustup target list --installed | grep -q x86_64-apple-darwin  || rustup target add x86_64-apple-darwin
        cargo build --manifest-path "$CORE_DIR/Cargo.toml" --release -p grouse-core \
            --target aarch64-apple-darwin
        cargo build --manifest-path "$CORE_DIR/Cargo.toml" --release -p grouse-core \
            --target x86_64-apple-darwin

        echo "== lipo: universal static library =="
        lipo -create \
            "$CORE_DIR/target/aarch64-apple-darwin/release/libgrouse_core.a" \
            "$CORE_DIR/target/x86_64-apple-darwin/release/libgrouse_core.a" \
            -output "$LIB_DIR/libgrouse_core.a"
    fi

    echo "== Rust: host DEBUG build (unstripped — this one carries the uniffi metadata) =="
    cargo build --manifest-path "$CORE_DIR/Cargo.toml" -p grouse-core --target "$HOST_TARGET"
fi

# Bindgen reads the metadata from a DYNAMIC library, so it needs the dylib, not the .a.
BINDGEN_INPUT="$CORE_DIR/target/$HOST_TARGET/debug/libgrouse_core.dylib"

[[ -f "$BINDGEN_INPUT" ]] || {
    echo "error: no $BINDGEN_INPUT — the crate must build a cdylib (Cargo.toml crate-type)" >&2
    exit 1
}

echo "== uniffi: Swift sources + C headers =="
mkdir -p "$GEN_SWIFT" "$GEN_INCLUDE"
"$UNIFFI_BINDGEN" --swift-sources --headers \
    "$BINDGEN_INPUT" "$GEN_SWIFT"
# bindgen writes .swift AND the two FFI headers into one directory; the headers belong in
# the C target's include/ (that is where SwiftPM looks for a C target's module).
# bindgen writes the Swift AND the C headers into one directory: the headers have to move
# into the C target's include/, which is where SwiftPM looks for a C target's module.
mv "$GEN_SWIFT"/*FFI.h "$GEN_INCLUDE"/ 2>/dev/null || {
    echo "error: bindgen produced no FFI headers — did it run against the dylib?" >&2
    exit 1
}

# Plain (non-framework) module map: one module per header, which is what
# `#if canImport(grouse_coreFFI)` in the generated Swift is asking for.
cat > "$GEN_INCLUDE/module.modulemap" <<'MAP'
module grouse_coreFFI {
    header "grouse_coreFFI.h"
    export *
}
module grouse_roam_coreFFI {
    header "grouse_roam_coreFFI.h"
    export *
}
MAP

echo "== SwiftPM: Package.swift for this checkout =="
sed "s|@LIBDIR@|$LIB_DIR|g" Package.swift.in > Package.swift

echo "== swift build =="
swift build 2>&1 | tail -20

echo
echo "Built. Run it:"
echo "  GROUSE_HOST=goose.gauvin.id GROUSE_PORT=443 GROUSE_KEY=… ./.build/debug/grouse-spike"
echo "(env vars: GROUSE_HOST, GROUSE_PORT, GROUSE_KEY, GROUSE_TLS=1|0, GROUSE_CWD, GROUSE_CACHE)"
